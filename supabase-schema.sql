alter table public.tickets add constraint tickets_case_type_check
  check (case_type in ('Request for Information','Quality Complaint','Marketing Contact','Consumer Feedback','Adverse Effect','Error Call'));
alter table public.tickets drop constraint if exists tickets_channel_check;
