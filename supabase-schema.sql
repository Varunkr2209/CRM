-- PulseDesk Careline CRM starter schema for Colombia (PostgreSQL).
-- Run in an approved Supabase project. Policies below are demo-wide; harden
-- access and validate Colombia-specific privacy requirements before use.
create extension if not exists pgcrypto;

create table if not exists public.team_members (
  id uuid primary key default gen_random_uuid(),
  auth_user_id uuid unique references auth.users(id) on delete set null,
  display_name text not null,
  email text unique not null,
  role text not null default 'agent' check (role in ('admin','agent')),
  created_at timestamptz not null default now()
);

alter table public.team_members
  add column if not exists auth_user_id uuid unique references auth.users(id) on delete set null;

create table if not exists public.contacts (
  id uuid primary key default gen_random_uuid(),
  full_name text not null,
  email text,
  phone text,
  end_market text not null default 'Colombia',
  city text,
  created_by uuid references auth.users(id),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.tickets (
  id uuid primary key default gen_random_uuid(),
  ticket_number bigint generated by default as identity unique,
  contact_id uuid references public.contacts(id) on delete set null,
  customer_name text not null,
  issue_summary text not null,
  category text not null default 'Other',
  case_type text not null default 'Request for Information',
  channel text not null default 'Care Line',
  brand text not null default 'VELO',
  product text,
  flavor text,
  nicotine_strength text,
  end_market text not null default 'Colombia',
  city text,
  priority text not null default 'Medium',
  status text not null default 'New',
  closure_reason text,
  assignee_id uuid references public.team_members(id) on delete set null,
  created_by uuid references auth.users(id),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

